public class Example {
    private int value;
    private String name;
    
    public Example(int v) {
        value = v;
        name = "";
    }
    
    public int getValue() {
        return value;
    }
    
    public void setValue(int v) {
        value = v;
    }
    
    public String getName() {
        return name;
    }
}

